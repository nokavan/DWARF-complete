#!/usr/bin/env python3
"""
Generates patched copies of CA campaign scripts so that dwarf-only mechanics also work for the
"Империя героев" culture. The patch is mechanical and checked: each listed file must contain the
expected number of dwarf-culture checks, otherwise generation fails (CA changed the file -> review).

  python3 -I mods/hero_empire_sotek/_gen/gen_overrides.py --scripts data_script.pack

Every  X:culture() == "wh_main_dwf_dwarfs"  becomes  X:culture():he_dwarfish()
where string.he_dwarfish(s) is true for the dwarf culture AND for he_hero_empire.
The patched file is placed at the same path, so the mod's copy replaces the vanilla one.
"""
import argparse
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from game_data import Pack  # noqa: E402

MOD = os.path.join(ROOT, "mods", "hero_empire_sotek")
NEEDLE = ':culture() == "wh_main_dwf_dwarfs"'
REPLACEMENT = ":culture():he_dwarfish()"

# vanilla path -> expected number of dwarf-culture checks
FILES = {
    "script/campaign/wh3_campaign_underdeep.lua": 9,   # Underdeeps (Глубины)
}

HEADER = """-- =====================================================================================
-- PATCHED COPY of CA's %(path)s  (vanilla sha1 %(sha)s)
-- Generated by mods/hero_empire_sotek/_gen/gen_overrides.py - DO NOT EDIT BY HAND.
-- Change: dwarf-culture checks also accept the culture he_hero_empire (Империя героев).
-- =====================================================================================
if not string.he_dwarfish then
	local he_dwarfish_cultures = { wh_main_dwf_dwarfs = true, he_hero_empire = true }
	function string.he_dwarfish(culture_key)
		return he_dwarfish_cultures[culture_key] == true
	end
end

"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scripts", required=True, help="game pack with the script/ folder (data_script.pack)")
    a = ap.parse_args()
    pack = Pack(a.scripts)
    for path, expected in FILES.items():
        src = pack.read(path).decode("utf-8")
        n = src.count(NEEDLE)
        if n != expected:
            sys.exit("%s: expected %d dwarf-culture checks, found %d - CA changed the file, review the patch" % (path, expected, n))
        patched = HEADER % {"path": path, "sha": hashlib.sha1(src.encode("utf-8")).hexdigest()} + src.replace(NEEDLE, REPLACEMENT)
        dst = os.path.join(MOD, path)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(patched)
        print("patched %s (%d checks)" % (path, n))


if __name__ == "__main__":
    main()
